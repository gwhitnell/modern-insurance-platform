-- Horizon Catalog metadata for the Modern Insurance Platform.
--
-- Prerequisites:
--   1. Terraform has created both environment databases and RAW tables.
--   2. dbt has built CLEAN and ANALYTICS in DEV and PRD.
--   3. `dbt run-operation create_semantic_views` has created the PRD semantic views.
--
-- Run this script as ACCOUNTADMIN after those steps. Object tagging might require
-- Enterprise Edition or higher. The script stores metadata only; do not put
-- customer values or other personal information in tag values or comments.

USE ROLE ACCOUNTADMIN;

CREATE SCHEMA IF NOT EXISTS PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE
  COMMENT = 'Governance metadata shared by the Modern Insurance Platform data product.';

CREATE TAG IF NOT EXISTS PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_DOMAIN
  ALLOWED_VALUES 'CUSTOMER', 'POLICY', 'CLAIMS', 'POLICY_LIFECYCLE', 'CROSS_DOMAIN'
  COMMENT = 'Business domain represented by an object.';

CREATE TAG IF NOT EXISTS PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_LAYER
  ALLOWED_VALUES 'SOURCE', 'CLEAN', 'CURATED', 'SEMANTIC'
  COMMENT = 'Logical layer occupied by an object.';

CREATE TAG IF NOT EXISTS PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.ENVIRONMENT
  ALLOWED_VALUES 'DEV', 'PRD'
  COMMENT = 'Delivery environment containing an object.';

CREATE TAG IF NOT EXISTS PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_PRODUCT
  COMMENT = 'Governed data product to which an object belongs.';

CREATE TAG IF NOT EXISTS PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS
  ALLOWED_VALUES 'SOURCE_ONLY', 'DRAFT', 'TRUSTED', 'DEPRECATED'
  COMMENT = 'Whether an object is approved for supported analytical use.';

CREATE TAG IF NOT EXISTS PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CONFIDENTIALITY
  ALLOWED_VALUES 'INTERNAL', 'CONFIDENTIAL', 'RESTRICTED'
  COMMENT = 'Highest confidentiality level of data contained by an object.';

CREATE TAG IF NOT EXISTS PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.PII_TYPE
  ALLOWED_VALUES 'CUSTOMER_IDENTIFIER', 'NAME', 'DATE_OF_BIRTH', 'EMAIL'
  COMMENT = 'Type of personal data held by a column.';

-- Environment and layer metadata inherited by child objects where applicable.
ALTER DATABASE DEV_MODERN_INSURANCE_PLATFORM SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.ENVIRONMENT = 'DEV',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_PRODUCT = 'MODERN_INSURANCE_PLATFORM';

ALTER DATABASE PRD_MODERN_INSURANCE_PLATFORM SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.ENVIRONMENT = 'PRD',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_PRODUCT = 'MODERN_INSURANCE_PLATFORM';

ALTER SCHEMA DEV_MODERN_INSURANCE_PLATFORM.RAW SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_LAYER = 'SOURCE',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'SOURCE_ONLY';
ALTER SCHEMA DEV_MODERN_INSURANCE_PLATFORM.CLEAN SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_LAYER = 'CLEAN',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'DRAFT';
ALTER SCHEMA DEV_MODERN_INSURANCE_PLATFORM.ANALYTICS SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_LAYER = 'CURATED',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'DRAFT';

ALTER SCHEMA PRD_MODERN_INSURANCE_PLATFORM.RAW SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_LAYER = 'SOURCE',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'SOURCE_ONLY';
ALTER SCHEMA PRD_MODERN_INSURANCE_PLATFORM.CLEAN SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_LAYER = 'CLEAN',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'DRAFT';
ALTER SCHEMA PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_LAYER = 'CURATED',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'TRUSTED';

-- Curated PRD assets. These are the supported entry points for consumers.
ALTER TABLE PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.DIM_CUSTOMER SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_DOMAIN = 'CUSTOMER',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'TRUSTED',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CONFIDENTIALITY = 'RESTRICTED';

ALTER TABLE PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.DIM_POLICY SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_DOMAIN = 'POLICY',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'TRUSTED',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CONFIDENTIALITY = 'CONFIDENTIAL';

ALTER TABLE PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.FCT_CLAIMS SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_DOMAIN = 'CLAIMS',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'TRUSTED',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CONFIDENTIALITY = 'CONFIDENTIAL';

ALTER TABLE PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.FCT_BUSINESS_EVENTS SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_DOMAIN = 'POLICY_LIFECYCLE',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'TRUSTED',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CONFIDENTIALITY = 'CONFIDENTIAL';

ALTER TABLE PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.FCT_POLICY_MONTHLY SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_DOMAIN = 'CROSS_DOMAIN',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'TRUSTED',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CONFIDENTIALITY = 'CONFIDENTIAL';

-- Personal-data metadata on the canonical customer dimension.
ALTER TABLE PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.DIM_CUSTOMER
  MODIFY COLUMN CUSTOMER_NK SET TAG PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.PII_TYPE = 'CUSTOMER_IDENTIFIER';
ALTER TABLE PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.DIM_CUSTOMER
  MODIFY COLUMN CUSTOMER_ID SET TAG PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.PII_TYPE = 'CUSTOMER_IDENTIFIER';
ALTER TABLE PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.DIM_CUSTOMER
  MODIFY COLUMN FIRST_NAME SET TAG PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.PII_TYPE = 'NAME';
ALTER TABLE PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.DIM_CUSTOMER
  MODIFY COLUMN LAST_NAME SET TAG PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.PII_TYPE = 'NAME';
ALTER TABLE PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.DIM_CUSTOMER
  MODIFY COLUMN DATE_OF_BIRTH SET TAG PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.PII_TYPE = 'DATE_OF_BIRTH';
ALTER TABLE PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.DIM_CUSTOMER
  MODIFY COLUMN EMAIL SET TAG PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.PII_TYPE = 'EMAIL';

-- Semantic interfaces used by Cortex Analyst and Snowflake Intelligence.
ALTER SEMANTIC VIEW PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.CLAIMS_SEMANTIC_VIEW SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_LAYER = 'SEMANTIC',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_DOMAIN = 'CLAIMS',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'TRUSTED',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CONFIDENTIALITY = 'CONFIDENTIAL';

ALTER SEMANTIC VIEW PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.INSURANCE_PERFORMANCE SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_LAYER = 'SEMANTIC',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_DOMAIN = 'CROSS_DOMAIN',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'TRUSTED',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CONFIDENTIALITY = 'CONFIDENTIAL';

ALTER SEMANTIC VIEW PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.CUSTOMER_SERVICE_LOOKUP SET TAG
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_LAYER = 'SEMANTIC',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.DATA_DOMAIN = 'CUSTOMER',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CERTIFICATION_STATUS = 'TRUSTED',
  PRD_MODERN_INSURANCE_PLATFORM.GOVERNANCE.CONFIDENTIALITY = 'RESTRICTED';

-- Verification: tag values and comments are searchable in Horizon Catalog.
SELECT *
FROM TABLE(
  PRD_MODERN_INSURANCE_PLATFORM.INFORMATION_SCHEMA.TAG_REFERENCES(
    'PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS.FCT_POLICY_MONTHLY',
    'TABLE'
  )
);

SHOW SEMANTIC VIEWS IN SCHEMA PRD_MODERN_INSURANCE_PLATFORM.ANALYTICS;
